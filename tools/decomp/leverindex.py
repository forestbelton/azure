#!/usr/bin/env python3
"""leverindex.py -- regenerate the index at the top of docs/matching-levers.md.

The file is 6.5k lines and every heading in it is a lever statement, so the
headings alone are a usable index: read it, then read only the section you
need, instead of paying for the whole document on every turn.

Rewrites the block between the INDEX markers in place. Run it after adding or
renaming a heading; `--check` exits 1 if the index is stale.

    python3 tools/decomp/leverindex.py
    python3 tools/decomp/leverindex.py --check
"""
import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.environ.get("AZURE_ROOT", os.path.dirname(os.path.dirname(HERE)))
DOC = os.path.join(PROJ, "docs/matching-levers.md")

BEGIN = "<!-- INDEX: generated by tools/decomp/leverindex.py -- do not edit by hand -->"
END = "<!-- END INDEX -->"


def build(lines):
    out = []
    for i, l in enumerate(lines, 1):
        m = re.match(r"^(#{2,3}) (.+?)\s*$", l)
        if not m:
            continue
        depth, title = len(m.group(1)), m.group(2)
        if title.startswith("Index"):
            continue
        out.append("%s- %s  `:%d`" % ("  " * (depth - 2), title, i))
    return out


def rebuild(text):
    """Insert or replace the index. Line numbers shift when the block's own
    size changes, so iterate to a fixed point."""
    for _ in range(10):
        new = rebuild_once(text)
        if new == text:
            return text
        text = new
    return text


def rebuild_once(text):
    lines = text.split("\n")
    index = build(lines)
    block = "\n".join([BEGIN, "", "## Index", "",
                       "One line per lever, with its line number. Read this,",
                       "then read only the section you need.", ""]
                      + index + ["", END])

    if BEGIN in text and END in text:
        pre = text[:text.index(BEGIN)]
        post = text[text.index(END) + len(END):]
        new = pre + block + post
    else:
        # first run: insert after the title and its opening paragraph
        i = text.index("\n## ")
        new = text[:i] + "\n" + block + "\n" + text[i:]
    return new


def main():
    text = io.open(DOC, encoding="utf-8").read()
    final = rebuild(text)
    levers = len(build(final.split("\n")))
    if final == text:
        print("index current (%d levers)" % levers)
        return 0
    if "--check" in sys.argv:
        print("index is STALE (%d levers); run leverindex.py" % levers)
        return 1
    io.open(DOC, "w", encoding="utf-8").write(final)
    print("wrote index: %d levers" % levers)
    return 0


if __name__ == "__main__":
    sys.exit(main())
