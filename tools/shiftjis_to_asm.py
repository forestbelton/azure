"""Turn a string-pool `.txt` into the `.rodata` listing the linker places.

The `.txt` is the source of truth; the `.s` beside it is generated, gitignored
and rebuilt by the `asrc/str/%.s: asrc/str/%.txt` rule in the Makefile. One
line per entry:

    LABEL[,LABEL...]=TEXT          the text, a NUL, then zeros to the next
                                   4-byte boundary -- what every pooled string
                                   in this game looks like.
    LABEL[,LABEL...]:nopad=TEXT    the text and its NUL, nothing after it. For
                                   an entry whose padding is not zeros, so the
                                   bytes have to be given rather than computed.
    LABEL[,LABEL...]:bytes=HH ...  exactly these bytes. No NUL, no padding. For
                                   a word in the middle of a pool that is not
                                   text at all, and for padding that is not
                                   zeros.

TEXT is UTF-8 and is encoded to Shift-JIS, which is how the game stores it. It
runs from the first `=` to the end of the line and is NOT stripped, because
U+3000 IDEOGRAPHIC SPACE is this game's space character and Python counts it as
whitespace;
`\\xNN` (ASCII only -- a byte over 0x7F has no Shift-JIS character to encode
from, so it belongs in a `:bytes=` entry), `\\\\` and `\\"` are escapes. The
label list may be empty, which emits the bytes under no label of their own --
the way to continue the entry on the line above.

Blank lines are dropped and `#` comments are passed through, so a pool's
provenance and findings live in the `.txt` with the strings they are about.
Keep the `Covers rom 0x...` line: splat/ext/hrodata.py reads it back out of
the GENERATED file on every split and warns when the subsegment has moved off
it, which is the only check against an `hrodata` listing silently no longer
covering the range the linker places it at.
"""

import argparse
import re
import sys
from typing import TextIO

ESCAPE_PATTERN = re.compile(r"\\(\\|\"|x[0-9a-fA-F]{2})")


def unescape(body: str) -> str:
    def sub(match: re.Match[str]) -> str:
        esc = match.group(1)
        if esc.startswith("x"):
            return chr(int(esc[1:], 16))
        return esc

    return ESCAPE_PATTERN.sub(sub, body)


def encode_text(value: str) -> bytes:
    """The game's own encoding for a pooled string, with its terminator."""
    return unescape(value).encode("shift-jis") + b"\x00"


def parse_bytes(value: str, where: str) -> bytes:
    """A whitespace-separated list of hex byte values, taken literally."""
    out = bytearray()
    for token in value.split():
        try:
            byte = int(token, 16)
        except ValueError:
            raise SystemExit(f"{where}: `{token}` is not a hex byte")
        if not 0 <= byte <= 0xFF:
            raise SystemExit(f"{where}: `{token}` is out of range for a byte")
        out.append(byte)
    return bytes(out)


def emit(data: bytes, pad: bool) -> str:
    literals = ", ".join("0x{:02x}".format(byte) for byte in data)
    lines = [f"  .byte {literals}"]
    if pad:
        lines.append("  .balign 4, 0")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("txtfile")
    parser.add_argument("--output", "-o", default="-")
    args = parser.parse_args()
    with open(args.txtfile, "r") as txtf:
        if args.output == "-":
            convert_shiftjis_file(txtf, sys.stdout, args.txtfile)
        else:
            with open(args.output, "w") as outf:
                convert_shiftjis_file(txtf, outf, args.txtfile)


def convert_shiftjis_file(inf: TextIO, outf: TextIO, name: str = "<stdin>") -> None:
    outf.write("# Code generated by tools/shiftjis_to_asm.py. DO NOT EDIT.\n\n")
    outf.write('.include "macro.inc"\n')
    outf.write(".section .rodata\n\n")
    for lineno, line in enumerate(inf, 1):
        # Only the newline comes off. str.strip() would also take a leading or
        # trailing U+3000 IDEOGRAPHIC SPACE, which Python counts as whitespace
        # and this game uses as its space character -- one description in the
        # item pool ends with one, and losing it shortens the pool by 4 bytes.
        line = line.rstrip("\r\n")
        where = f"{name}:{lineno}"
        if not line.strip():
            continue
        if line.lstrip().startswith("#"):
            outf.write(f"{line.rstrip()}\n")
            continue
        head, sep, value = line.partition("=")
        if not sep:
            raise SystemExit(f"{where}: no `=`, so this is neither an entry nor a comment")
        labels, _, form = head.partition(":")
        for label in labels.split(","):
            label = label.strip()
            if label:
                outf.write(f"dlabel {label}\n")
        if form == "":
            outf.write(emit(encode_text(value), pad=True))
        elif form == "nopad":
            outf.write(emit(encode_text(value), pad=False))
        elif form == "bytes":
            outf.write(emit(parse_bytes(value, where), pad=False))
        else:
            raise SystemExit(f"{where}: unknown entry form `:{form}`")
        outf.write("\n")


if __name__ == "__main__":
    main()
