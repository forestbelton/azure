#!/usr/bin/env python3
"""permimport.py FUNC -- scaffold nonmatchings/FUNC/ for decomp-permuter.

decomp-permuter's own import.py derives the compile command from
`make --always-make --dry-run`, so the source has to be a build input: for a
parked function that means dropping it into csrc/, which the landing gate
forbids. It also picks up only the first step of this project's pipeline
(the compiler's `-S`) and writes assembly text to the .o path, so every objdump then
fails with "file format not recognized".

This writes the five files directly instead, from the park source and the
splat listing -- or, with --source, from any candidate file you already have,
so a function that has never been parked can be permuted without inventing a
park for it:

    base.c        the park source, preprocessed with -DPERMUTER
    target.o      the splat listing assembled at the unit's own gas -G
    compile.sh    the full compiler -> maspsx -> as pipeline for that unit
    settings.toml func_name and compiler_type
    function.txt  the function name

    python3 tools/decomp/permimport.py func_8004D880
    python3 tools/decomp/permimport.py func_800CC644 --source scratch/cand.c
    python3 tools/decomp/permrun.py func_8004D880 --minutes 60

--source takes any file that DEFINES the function and compiles: a scratch
candidate, or the whole merged unit copy an agent measured in. Without it the
source is docs/near-misses/FUNC.c as before. On 2026-11-02 an agent had to
hand-write all five files because its candidate was 44 words of 46 with no
park, which is exactly the case this flag is for.
"""
import io
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ = os.environ.get("AZURE_ROOT", os.path.dirname(os.path.dirname(HERE)))
sys.path.insert(0, HERE)
import asmlib  # noqa: E402

AS = os.environ.get("AS", "mips64-linux-gnu-as")


def unit_for(func):
    """The unit whose INCLUDE_ASM stub owns this function."""
    for name in sorted(os.listdir(os.path.join(PROJ, "csrc"))):
        if not name.endswith(".c"):
            continue
        text = io.open(os.path.join(PROJ, "csrc", name), encoding="utf-8",
                       errors="replace").read()
        if re.search(r"INCLUDE_ASM\([^)]*\b%s\b" % func, text):
            return name[:-2]
    return None


def preprocess(park, out, cc="tools/cdkgcc"):
    """cpppsx the park source so pycparser sees no project macros."""
    # -Icsrc was missing until 2026-11-13, so no park that includes a header
    # living in csrc/ -- main_twin.h, every park in the 0x80400000 twin, which
    # is the only block with work left -- could be imported at all. An agent
    # working func_804034D8 had to rewrite the park's includes as
    # ../../csrc/... to get a permuter run at all. The include list is taken
    # from asmlib.CFLAGS now rather than spelled again here, because this is
    # the THIRD tool in this directory found carrying its own drifted copy
    # (tools/decomp/dump.sh had both this and a hardcoded compiler).
    incs = [f for f in asmlib.CFLAGS if f.startswith("-I")]
    r = subprocess.run(
        [os.path.join(PROJ, cc), "-E", "-G8"] + incs + ["-DPERMUTER", park],
        cwd=PROJ, capture_output=True, text=True)
    if r.returncode or not r.stdout.strip():
        return "preprocess failed: %s" % (r.stderr.strip().split("\n")[0][:120])
    # cc1psx output is CRLF; pycparser wants plain newlines.
    io.open(out, "w", encoding="utf-8", newline="\n").write(
        r.stdout.replace("\r\n", "\n"))
    return None


def assemble_target(unit, func, out):
    """Assemble the splat listing for this function into target.o."""
    asm = os.path.join(PROJ, "asm/nonmatchings", unit, func + ".s")
    if not os.path.exists(asm):
        return "no splat listing at %s" % os.path.relpath(asm, PROJ)
    wrapper = io.open(asm, encoding="utf-8", errors="replace").read()
    text = '.include "macro.inc"\n.set noat\n.set noreorder\n' + wrapper
    src = out[:-2] + ".s"
    io.open(src, "w", encoding="utf-8").write(text)
    r = subprocess.run(
        [AS, "-EL", "-32", "-march=r3000", "-mtune=r3000", "-no-pad-sections",
         "-O1", "-G%d" % asmlib.gas_g_for_unit(unit),
         "-Iinclude", "-I" + os.path.join(PROJ, "include"), src, "-o", out],
        cwd=PROJ, capture_output=True, text=True)
    if r.returncode:
        return "assembling the listing failed: %s" % (
            r.stderr.strip().split("\n")[0][:160])
    return None


COMPILE_SH = """#!/usr/bin/env bash
# Generated by tools/decomp/permimport.py for {unit}. The permuter calls this
# as `compile.sh INPUT_C something OUTPUT_O`.
set -euo pipefail
INPUT="$(realpath "$1")"
OUTPUT="$(realpath "$3")"
PROJ="{proj}"
cd "$PROJ"
S="$(mktemp --suffix=.s)"
trap 'rm -f "$S"' EXIT
{cc} -O2 -G{cc1g} -Iinclude -Ipsyq/include -Icsrc -DPERMUTER -S "$INPUT" -o "$S"
python3 vendor/maspsx/maspsx.py \\
    --aspsx-version=2.56 --force-stdin --run-assembler {mflags}\\
    --gnu-as-path="${{AS:-{as_}}}" --use-comm-section {gflags} \\
    -EL -32 -march=r3000 -mtune=r3000 -no-pad-sections -O1 \\
    -o "$OUTPUT" < "$S"
"""

SETTINGS = """func_name = "{func}"
compiler_type = "gcc"
"""


def main():
    argv = sys.argv[1:]
    source = None
    rest = []
    i = 0
    while i < len(argv):
        a = argv[i]
        if a == "--source":
            if i + 1 >= len(argv):
                print("permimport: --source needs a path")
                return 2
            source = argv[i + 1]
            i += 2
            continue
        if a.startswith("--source="):
            source = a.split("=", 1)[1]
            i += 1
            continue
        if not a.startswith("--"):
            rest.append(a)
        i += 1
    args = rest
    if not args:
        print((__doc__ or "").strip().split("\n\n")[0])
        return 2
    func = args[0]
    unit = unit_for(func)
    if not unit:
        print("permimport: no INCLUDE_ASM stub for %s in csrc/" % func)
        return 1
    if source:
        park = source if os.path.isabs(source) else os.path.join(PROJ, source)
        if not os.path.exists(park):
            print("permimport: no source at %s" % source)
            return 1
        txt = io.open(park, encoding="utf-8", errors="replace").read()
        if func not in txt:
            print("permimport: %s does not mention %s" % (source, func))
            return 1
    else:
        park = os.path.join(PROJ, "docs/near-misses", func + ".c")
        if not os.path.exists(park):
            print("permimport: no park source at %s -- pass --source FILE to "
                  "permute a candidate that has never been parked"
                  % os.path.relpath(park, PROJ))
            return 1

    d = os.path.join(PROJ, "nonmatchings", func)
    os.makedirs(d, exist_ok=True)

    # Two compilers in the tree as of 2026-11-11; the unit picks one.
    cc = asmlib.cc1_for_unit(unit)

    err = preprocess(park, os.path.join(d, "base.c"), cc)
    if err:
        print("permimport: " + err)
        return 1
    err = assemble_target(unit, func, os.path.join(d, "target.o"))
    if err:
        print("permimport: " + err)
        return 1

    gasG = asmlib.gas_g_for_unit(unit)
    cc1G = asmlib.cc1_g_for_unit(unit)
    # maspsx forces gas to -G0 unless the unit is one of the carved ones.
    # An OVERLAY unit is compiled at cc1psx -G0 and passes maspsx -G0 too, so
    # that maspsx makes no small-data decisions of its own on a unit that has
    # none; mirror the Makefile rather than the resident executable's -G8.
    if cc1G == 0:
        gflags = "-G0"
    elif gasG == 0:
        gflags = "-G8"
    else:
        gflags = "--dont-force-G0 -G%d" % gasG
    # THE UNIT'S OWN maspsx FLAGS. Without these the candidate is assembled
    # differently from the target.o beside it: ovl_main_80400000 is built with
    # --expand-div, so its two divisions carry the full aspsx check sequence
    # (bnez/break 0x7, bne/lui 0x8000/bne/break 0x6) in the TARGET and not in
    # the candidate. Found 2026-11-13 after a 40-minute run on func_804034D8
    # reported base=1810 for a source that ovlverify.py measures at 2
    # differing, and returned three "improvements" that verify at 8 and 12.
    # asmlib's own helper already warned this costs 18 words on one function
    # and says nothing about why; the permuter does not even say that much,
    # it just optimises the wrong objective for an hour.
    mflags = " ".join(asmlib.maspsx_extra_for_unit(unit))
    if mflags:
        mflags += " "
    sh = os.path.join(d, "compile.sh")
    io.open(sh, "w", encoding="utf-8").write(COMPILE_SH.format(
        unit=unit, proj=PROJ, as_=AS, gflags=gflags, cc1g=cc1G, cc=cc,
        mflags=mflags))
    os.chmod(sh, 0o755)
    io.open(os.path.join(d, "settings.toml"), "w", encoding="utf-8").write(
        SETTINGS.format(func=func))
    io.open(os.path.join(d, "function.txt"), "w", encoding="utf-8").write(
        func + "\n")

    print("%s: unit %s, cc1psx -G%d, gas -G%d, source %s -> %s" % (
        func, unit, cc1G, gasG, os.path.relpath(park, PROJ),
        os.path.relpath(d, PROJ)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
