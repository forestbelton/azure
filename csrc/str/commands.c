/*
 * The familiar-command and menu-verb pool: 35 strings of full-width Shift-JIS
 * in ROM order, then one seventeen-byte index table.
 *
 * Covers rom 0x001E10..0x002164 (vram 0x8002E610..0x8002E964).
 *
 * Every one of the 35 strings is pointed at from a table inside `game_data`,
 * at rom 0x044EC0..0x044F68 (vram 0x800716C0..0x80071768) -- four runs of
 * them, in no particular order -- and those 35 pointer targets are exactly the
 * 35 string starts, which is what fixes the object boundaries here without
 * guessing. Only the first is reached by a relocated symbol; the rest are bare
 * addresses in that table, so they would survive a wrong split silently. The
 * coverage test (docs/data-map.md) is clean: every byte of 0x1E10..0x2150 is
 * inside one of the 35 strings or is its NUL-and-align padding.
 *
 * The content is three groups in one pool: the four AI-behaviour descriptions
 * a familiar's Change-AI screen shows, the single-word menu verbs, and the
 * fusion prompts.
 *
 * Each entry is a separate object, so the compiler's own `.align 2` supplies
 * the zero padding up to the next 4-byte boundary. ORDER IS THE LAYOUT:
 * cc1psx emits file-scope objects in source order, so moving a definition
 * moves the bytes. The last entry carries an explicit size where the pool
 * needs trailing padding, because nothing follows it to align against.
 */

