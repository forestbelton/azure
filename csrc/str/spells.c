/*
 * The spell description-and-name pool: 101 strings of full-width Shift-JIS in
 * ROM order, then the two engine primitive templates.
 *
 * Covers rom 0x000EFC..0x001DF8 (vram 0x8002D6FC..0x8002E5F8).
 *
 * 96 of the strings are the spell pool proper, alternating a description with
 * the short name it belongs to, the same shape as csrc/str/items.c -- and five
 * of the pairs carry a display name as well, which is why the alternation is
 * not exact. The last five entries are not spells: "ｍｏｎｓｔｅｒ．", two
 * inventory messages, and the two Monsbaiya lines the architect speaks.
 *
 * The object boundaries are measured, not guessed, the same three ways as
 * csrc/str/speakers.c: 101 pointer targets from `game_data`, 101 NUL-walked
 * string starts, the two sets identical, and no uncovered non-zero byte in
 * 0xEFC..0x1DD8. None of the pointers is a relocated symbol.
 *
 * D_8002E5D8 and D_8002E5E8 ARE in this pool, at its very end, and that is
 * why this unit includes types.h and not common.h.
 *
 * The definitions have to be `const` or cc1psx emits them under .data and the
 * pool comes out 32 bytes short. include/structs.h declares them `u32 []`,
 * and it still does ON PURPOSE: six units copy them out through `u32 *`
 * locals, and const-qualifying those locals so the header could take the
 * const CHANGES gcc 2.7.2's CODEGEN. Measured 2026-11-14 -- csrc/unk_1C540.c
 * came out 8 bytes short and shifted every jump table after it, main.bin
 * broke at 0x25D0A8 and town.bin at 0x031828. So the const stops at this
 * file's own boundary, and the two declarations never meet the definition in
 * one translation unit. types.h is all this unit needs anyway.
 *
 * Each entry is a separate object, so the compiler's own `.align 2` supplies
 * the zero padding up to the next 4-byte boundary. ORDER IS THE LAYOUT:
 * cc1psx emits file-scope objects in source order, so moving a definition
 * moves the bytes.
 */

